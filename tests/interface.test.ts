import { test } from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';

test('language, theme, tone, weekly report and contradiction confirmation work together',async()=>{
 const dom=new JSDOM('<!DOCTYPE html><html><body></body></html>',{url:'http://localhost:3000'});
 Object.assign(globalThis,{window:dom.window,document:dom.window.document,HTMLElement:dom.window.HTMLElement,Element:dom.window.Element,localStorage:dom.window.localStorage,IS_REACT_ACT_ENVIRONMENT:true});
 Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true});
 class ResizeObserverStub {observe(){}unobserve(){}disconnect(){}}
 Object.assign(globalThis,{ResizeObserver:ResizeObserverStub});
 localStorage.setItem('aisana-journal-v1',JSON.stringify({state:{entries:[],initialized:true},version:0}));
 const React=await import('react');const {render,screen,fireEvent,cleanup,within}=await import('@testing-library/react');
 const Home=(await import('../src/app/page')).default;
 render(React.createElement(Home));
 fireEvent.click(screen.getByRole('button',{name:'Настройки'}));
 fireEvent.change(screen.getByLabelText('Язык интерфейса'),{target:{value:'en'}});
 assert.ok(screen.getByRole('heading',{name:'Settings'}));
 fireEvent.click(screen.getByRole('button',{name:'Dark'}));
 assert.equal(document.documentElement.dataset.theme,'dark');assert.equal(document.documentElement.lang,'en');
 fireEvent.change(screen.getByLabelText('Assistant tone',{exact:false}),{target:{value:'coach'}});
 assert.equal(JSON.parse(localStorage.getItem('aisana-preferences-v1')!).state.tone,'coach');
 fireEvent.change(screen.getByLabelText('Interface language'),{target:{value:'kk'}});
 assert.ok(screen.getByRole('heading',{name:'Баптаулар'}));
 fireEvent.change(screen.getByLabelText('Интерфейс тілі'),{target:{value:'en'}});
 fireEvent.click(screen.getByRole('button',{name:'Close'}));
 fireEvent.click(screen.getByRole('button',{name:'My week'}));
 assert.ok(screen.getByText('No entries this week yet.'));
 fireEvent.click(screen.getByRole('button',{name:'New entry'}));
 fireEvent.change(screen.getByLabelText("What's happening with your studies and mood?"),{target:{value:'I studied all day and I am tired.'}});
 fireEvent.change(screen.getByRole('slider',{name:/Study time/}),{target:{value:'0'}});
 fireEvent.click(screen.getByRole('button',{name:'Understand how I feel'}));
 assert.ok(screen.getByRole('alert').textContent?.includes('selected 0 hours'));
 assert.equal(JSON.parse(localStorage.getItem('aisana-journal-v1')!).state.entries.length,0);
 fireEvent.click(screen.getByLabelText('Continue with these details'));
 fireEvent.click(screen.getByRole('button',{name:'Understand how I feel'}));
 const result=screen.getByRole('dialog');
 assert.ok(within(result).getByRole('heading',{name:'Your entry analysis'}));
 assert.ok(result.textContent?.includes('Clarifications confirmed by the user.'));
 assert.ok(result.textContent?.includes('Your next step:'));
 const saved=JSON.parse(localStorage.getItem('aisana-journal-v1')!).state.entries;
 assert.equal(saved.length,1);assert.deepEqual(saved[0].clarifications,['study-all-day']);
 fireEvent.click(screen.getByRole('button',{name:'Got it, thanks'}));
 assert.ok(screen.getByRole('button',{name:'Download report'}));
 cleanup();render(React.createElement(Home));
 assert.equal(document.documentElement.dataset.theme,'dark');
 assert.ok(screen.getByRole('button',{name:'My journal'}));
 fireEvent.click(screen.getByRole('button',{name:'My journal'}));
 assert.ok(screen.getByText('I studied all day and I am tired.'));
 cleanup();dom.window.close();
});
